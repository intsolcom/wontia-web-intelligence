-- WWI — Carritos abandonados y recuperación visual.
-- Multi-tenant. Idempotente. No modifica store_carts ni store_orders.

CREATE TABLE IF NOT EXISTS store_abandoned_carts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    site_id INT NOT NULL DEFAULT 1,
    session_id VARCHAR(64) NOT NULL,
    visitor_hash VARCHAR(64) NULL,
    customer_id INT NULL,
    customer_name VARCHAR(255) NULL,
    customer_email VARCHAR(255) NULL,
    items JSON NULL,
    qty INT NOT NULL DEFAULT 0,
    value_cents BIGINT NOT NULL DEFAULT 0,
    currency VARCHAR(5) NOT NULL DEFAULT 'COP',
    source VARCHAR(120) NULL,
    medium VARCHAR(120) NULL,
    campaign VARCHAR(160) NULL,
    content VARCHAR(160) NULL,
    term VARCHAR(160) NULL,
    fbclid VARCHAR(255) NULL,
    gclid VARCHAR(255) NULL,
    landing_url VARCHAR(500) NULL,
    last_page VARCHAR(500) NULL,
    device VARCHAR(20) NULL,
    status ENUM('active','abandoned','contacted','recovered','converted','dismissed') NOT NULL DEFAULT 'active',
    recovery_channel VARCHAR(20) NULL,
    recovery_sent_at DATETIME NULL,
    recovered_order_uuid CHAR(36) NULL,
    recovered_value_cents BIGINT NULL,
    recovered_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY site_session (site_id, session_id),
    KEY idx_site_status (site_id, status, updated_at),
    KEY idx_site_customer (site_id, customer_id),
    KEY idx_site_recovered (site_id, recovered_order_uuid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
