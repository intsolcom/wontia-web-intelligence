-- WWI Tracking & Conversion Brick — ledger de eventos y atribución por pedido.
-- Idempotente. No modifica tablas existentes de SEO, store ni analytics.

CREATE TABLE IF NOT EXISTS tracking_events (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    site_id INT NOT NULL,
    event_id VARCHAR(80) NOT NULL,
    event_name VARCHAR(40) NOT NULL,
    platform VARCHAR(20) NOT NULL,
    destination_event VARCHAR(40) NOT NULL,
    session_id VARCHAR(64) NULL,
    visitor_hash VARCHAR(64) NULL,
    order_uuid CHAR(36) NULL,
    order_number VARCHAR(30) NULL,
    consent_snapshot VARCHAR(120) NULL,
    params JSON NULL,
    value_cents BIGINT NULL,
    currency CHAR(3) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'generated',
    error VARCHAR(255) NULL,
    occurred_at DATETIME NOT NULL,
    dispatched_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY site_event_platform (site_id, event_id, platform),
    KEY idx_tracking_site_name (site_id, event_name, created_at),
    KEY idx_tracking_site_order (site_id, order_uuid),
    KEY idx_tracking_platform_status (site_id, platform, status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tracking_order_attribution (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    site_id INT NOT NULL,
    order_uuid CHAR(36) NOT NULL,
    order_number VARCHAR(30) NULL,
    first_source VARCHAR(120) NULL,
    first_medium VARCHAR(120) NULL,
    first_campaign VARCHAR(160) NULL,
    first_content VARCHAR(160) NULL,
    first_term VARCHAR(160) NULL,
    first_fbclid VARCHAR(255) NULL,
    first_gclid VARCHAR(255) NULL,
    first_landing_url VARCHAR(500) NULL,
    first_seen_at DATETIME NULL,
    last_source VARCHAR(120) NULL,
    last_medium VARCHAR(120) NULL,
    last_campaign VARCHAR(160) NULL,
    last_content VARCHAR(160) NULL,
    last_term VARCHAR(160) NULL,
    last_fbclid VARCHAR(255) NULL,
    last_gclid VARCHAR(255) NULL,
    last_landing_url VARCHAR(500) NULL,
    last_seen_at DATETIME NULL,
    consent_analytics TINYINT NOT NULL DEFAULT 0,
    consent_marketing TINYINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY site_order_attribution (site_id, order_uuid),
    KEY idx_tracking_attribution_created (site_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
