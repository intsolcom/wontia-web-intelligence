-- WWI SEO Tracking — eventos de visitantes, links, CTA, formularios (envíos efectivos)
CREATE TABLE IF NOT EXISTS seo_tracking_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  site_id INT NOT NULL,
  session_id VARCHAR(64) NOT NULL,
  type VARCHAR(32) NOT NULL COMMENT 'page_view|page_leave|link_click|cta_click|form_submit|outbound',
  page_url VARCHAR(500) NOT NULL DEFAULT '',
  target VARCHAR(500) DEFAULT NULL,
  label VARCHAR(255) DEFAULT NULL,
  referrer VARCHAR(500) DEFAULT NULL,
  utm JSON DEFAULT NULL,
  duration_ms INT DEFAULT NULL,
  scroll_pct TINYINT DEFAULT NULL,
  device VARCHAR(16) DEFAULT NULL,
  os VARCHAR(32) DEFAULT NULL,
  browser VARCHAR(32) DEFAULT NULL,
  country CHAR(2) DEFAULT NULL,
  ip_hash CHAR(64) DEFAULT NULL,
  is_bot TINYINT(1) NOT NULL DEFAULT 0,
  is_internal TINYINT NOT NULL DEFAULT 0,
  internal_reason VARCHAR(40) DEFAULT NULL,
  device_id VARCHAR(64) DEFAULT NULL,
  visitor_hash VARCHAR(64) DEFAULT NULL,
  landing_url VARCHAR(500) DEFAULT NULL,
  utm_source VARCHAR(120) DEFAULT NULL,
  utm_medium VARCHAR(120) DEFAULT NULL,
  utm_campaign VARCHAR(160) DEFAULT NULL,
  utm_term VARCHAR(160) DEFAULT NULL,
  utm_content VARCHAR(160) DEFAULT NULL,
  fbclid VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_site_type (site_id, type),
  INDEX idx_site_created (site_id, created_at),
  INDEX idx_session (site_id, session_id),
  INDEX idx_target (site_id, target(191)),
  INDEX idx_site_internal (site_id, is_internal, created_at),
  INDEX idx_site_visitor (site_id, visitor_hash),
  INDEX idx_site_utm (site_id, utm_source, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
