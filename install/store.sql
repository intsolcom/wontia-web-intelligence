-- WWI STORE — Ecommerce por tenant (Fase 3)
-- Todas las tablas multi-tenant con site_id = @site_id. Idempotente.

CREATE TABLE IF NOT EXISTS store_categories (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    name VARCHAR(150) NOT NULL,
    slug VARCHAR(150) NOT NULL,
    description TEXT,
    image VARCHAR(500),
    parent_id INT NULL,
    path VARCHAR(255) NULL,
    level TINYINT NOT NULL DEFAULT 1,
    icon VARCHAR(40) NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'sonika',
    external_key VARCHAR(120) NULL,
    sort_order INT DEFAULT 0,
    is_active TINYINT DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY site_cat_path (site_id, path),
    KEY idx_store_cat_slug (site_id, slug)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS store_products (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    category_id INT NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    description TEXT,
    short_description VARCHAR(500),
    price_cents INT NOT NULL DEFAULT 0,
    compare_price_cents BIGINT DEFAULT 0,
    currency VARCHAR(5) DEFAULT 'COP',
    sku VARCHAR(80),
    stock INT DEFAULT 0,
    track_stock TINYINT DEFAULT 1,
    weight_grams INT DEFAULT 0,
    images JSON,
    tags JSON,
    status ENUM('draft','active','archived') DEFAULT 'draft',
    is_featured TINYINT DEFAULT 0,
    seo_title VARCHAR(255),
    seo_description VARCHAR(500),
    sort_order INT DEFAULT 0,
    vendor VARCHAR(150) NULL,
    product_type VARCHAR(150) NULL,
    catalog_handle VARCHAR(255) NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'local',
    source_tags JSON NULL,
    category_locked TINYINT(1) NOT NULL DEFAULT 0,
    category_source VARCHAR(20) NOT NULL DEFAULT '',
    catalog_synced_at DATETIME NULL,
    free_shipping TINYINT(1) NOT NULL DEFAULT 0,
    tax_exempt TINYINT(1) NOT NULL DEFAULT 0,
    visibility VARCHAR(20) NOT NULL DEFAULT 'public',
    allowed_ips TEXT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY site_store_prod_slug (site_id, slug),
    KEY idx_store_prod_status (site_id, status),
    KEY idx_store_prod_cat (site_id, category_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS store_variants (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    product_id INT NOT NULL,
    name VARCHAR(150) NOT NULL,
    options JSON,
    price_cents BIGINT DEFAULT 0,
    stock INT DEFAULT 0,
    sku VARCHAR(80),
    sort_order INT DEFAULT 0,
    is_active TINYINT DEFAULT 1,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    KEY idx_store_var_prod (site_id, product_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS store_customers (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    name VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(50),
    document VARCHAR(50),
    address JSON,
    notes TEXT,
    orders_count INT DEFAULT 0,
    total_spent_cents INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_store_cust_email (site_id, email),
    KEY idx_store_cust_phone (site_id, phone)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS store_orders (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    uuid CHAR(36) NOT NULL,
    order_number VARCHAR(30),
    customer_id INT NULL,
    customer_name VARCHAR(255),
    customer_email VARCHAR(255),
    customer_phone VARCHAR(50),
    customer_document VARCHAR(50),
    quote_code VARCHAR(40) COLLATE utf8mb4_unicode_ci NULL,
    shipping_address JSON,
    shipping_zone_id INT NULL,
    subtotal_cents BIGINT DEFAULT 0,
    shipping_cents BIGINT DEFAULT 0,
    discount_cents BIGINT DEFAULT 0,
    total_cents BIGINT DEFAULT 0,
    currency VARCHAR(5) DEFAULT 'COP',
    payment_method VARCHAR(30) DEFAULT 'cod',
    payment_status ENUM('pending','paid','failed','refunded') DEFAULT 'pending',
    fulfillment_status ENUM('new','confirmed','preparing','shipped','delivered','cancelled') DEFAULT 'new',
    provider_ref VARCHAR(255),
    notes TEXT,
    admin_notes TEXT,
    ip_hash VARCHAR(64) NULL,
    affiliate_ref VARCHAR(64) NULL,
    is_internal TINYINT NOT NULL DEFAULT 0,
    internal_reason VARCHAR(40) NULL,
    stock_released TINYINT DEFAULT 0,
    paid_at DATETIME NULL,
    archived_at DATETIME NULL,
    is_test TINYINT NOT NULL DEFAULT 0,
    archive_reason VARCHAR(40) NULL,
    archived_by INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY site_store_order_uuid (site_id, uuid),
    KEY idx_store_orders_payment (site_id, payment_status),
    KEY idx_store_orders_fulfillment (site_id, fulfillment_status),
    KEY idx_store_orders_archived (site_id, archived_at),
    KEY idx_store_orders_test (site_id, is_test),
    KEY idx_store_orders_email (site_id, customer_email)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS store_order_items (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    order_id INT NOT NULL,
    product_id INT NULL,
    variant_id INT NULL,
    sku VARCHAR(120) NULL,
    product_ref VARCHAR(255) NULL,
    name VARCHAR(255),
    variant_name VARCHAR(150),
    price_cents BIGINT DEFAULT 0,
    qty INT DEFAULT 1,
    subtotal_cents BIGINT DEFAULT 0,
    weight_grams INT NOT NULL DEFAULT 0,
    image VARCHAR(500),
    KEY idx_store_items_order (site_id, order_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS store_shipping_zones (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    name VARCHAR(150) NOT NULL,
    regions VARCHAR(500),
    cost_cents INT DEFAULT 0,
    free_over_cents INT DEFAULT 0,
    eta_days VARCHAR(50),
    is_active TINYINT DEFAULT 1,
    sort_order INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_store_zones_active (site_id, is_active)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS store_order_events (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL DEFAULT 1,
    order_id INT NOT NULL,
    event VARCHAR(40) NOT NULL,
    from_value VARCHAR(80) NULL,
    to_value VARCHAR(80) NULL,
    reason VARCHAR(120) NULL,
    user_id INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    KEY idx_store_order_events_order (site_id, order_id, id),
    KEY idx_store_order_events_event (site_id, event)
) ENGINE=InnoDB;

-- Bloque editorial complementario por producto (guía rápida, casos de uso y FAQ).
CREATE TABLE IF NOT EXISTS product_seo_content (
    id INT AUTO_INCREMENT PRIMARY KEY,
    site_id INT NOT NULL,
    product_id INT NOT NULL,
    intro TEXT NULL,
    use_cases_json JSON NULL,
    faq_json JSON NULL,
    meta_description VARCHAR(500) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'draft',
    source VARCHAR(30) NOT NULL DEFAULT 'tia',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_site_product (site_id, product_id),
    KEY idx_site_status (site_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
